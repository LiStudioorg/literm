package com.literm.listudioorg.logic

import android.content.Context

/** 悬浮球快捷键开关的 SharedPreferences 存取，默认关闭。 */
object FloatingShortcutsPrefs {
    private const val PREFS_NAME = "literm_settings"
    private const val KEY_ENABLED = "floating_shortcuts_enabled"

    /** 读取开关状态。 */
    fun isEnabled(context: Context): Boolean =
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .getBoolean(KEY_ENABLED, false)

    /** 保存开关状态，设置页与 MainActivity 都会写。 */
    fun setEnabled(context: Context, enabled: Boolean) {
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putBoolean(KEY_ENABLED, enabled)
            .apply()
    }
}
